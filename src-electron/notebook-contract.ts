export type NotebookRequest = { params?: Record<string, string>; query?: Record<string, string>; body?: unknown; bodyUploadId?: string; form?: Array<{ name: string; value?: string; uploadId?: string; textUploadId?: string }> };
export function findNotebookRoute(method: string, pathname: string) {
  for (const route of NOTEBOOK_ROUTES) {
    if (route.method !== method.toUpperCase()) continue;
    const names = [...route.path.matchAll(/\{(\w+)\}/g)].map(match => match[1]);
    const match = new RegExp('^' + route.path.replace(/\{\w+\}/g, '([^/]+)') + '$').exec(pathname);
    if (match) return { route, params: Object.fromEntries(names.map((name, i) => [name, decodeURIComponent(match[i + 1])])) };
  }
  throw new Error('NOTEBOOK_OPERATION_UNAVAILABLE');
}
